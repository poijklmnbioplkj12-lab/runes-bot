@dp.message(Command("rune"))
async def cmd_rune(message: types.Message):
    name, desc = random.choice(list(RUNES.items()))
    await message.answer(f"🔮 **Ваша руна дня:**\n\n*{name}*\n\n{desc}")

@dp.message(Command("spread"))
async def cmd_spread(message: types.Message):
    selected = random.sample(list(RUNES.items()), 3)
    r1, r2, r3 = selected[0], selected[1], selected[2]
    
    text = (
        "📜 **Ваш расклад на 3 руны:**\n\n"
        f"1️⃣ **Прошлое:** *{r1[0]}*\n{r1[1]}\n\n"
        f"2️⃣ **Настоящее:** *{r2[0]}*\n{r2[1]}\n\n"
        f"3️⃣ **Будущее:** *{r3[0]}*\n{r3[1]}"
    )
    await message.answer(text)

@dp.message(Command("list"))
async def cmd_list(message: types.Message):
    runes_list = "\n".join([f"• {name}" for name in RUNES.keys()])
    await message.answer(f"📚 **Все 24 руны Старшего Футарка:**\n\n{runes_list}")

